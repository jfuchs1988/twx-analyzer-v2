package io.twxav2.analysis.bizdata;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.twxav2.ingest.TwxParseResult;

import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Data model (B2f): the snapshot's Business Data Types - prefix 12 (twClass).
 * The attribute structure lives as XSD-like JSON in the {@code <jsonData>} element
 * (entity-encoded); primitive types carry the Lombardi namespace
 * ({@code {http://lombardi.ibm.com/schema/}String} etc.).
 *
 * three kinds, recognizable in the JSON: <em>wrapper</em> = wrapped message
 * (rootElement + itemRef, generated by the designer), <em>imported</em> = created
 * from a Swagger/XSD import (targetNamespace "externalservice/swagger"),
 * <em>manual</em> = the team's domain data model. Documentation/usage rules
 * judge only the manual types - the team is not responsible for generated ones.
 * Loads exactly once per parse result (cache like BpdModels/CoachViews).
 */
public final class BusinessData {

    /** An attribute/element of the schema; hasDoc = documentation entry in annotation.documentation. */
    public record Prop(String name, String type, boolean hasDoc) { }

    /** A Business Data Type (twClass) with parsed-out jsonData. */
    public record Type(TwxParseResult.ParsedObject object, String name, boolean wrapper,
                       boolean imported, boolean shared, boolean rootHasDoc,
                       List<Prop> props) {

        /** Manual domain data type (neither wrapper nor import). */
        public boolean manual() {
            return !wrapper && !imported;
        }
    }

    private static final Pattern JSON_DATA =
            Pattern.compile("<jsonData>(.*?)</jsonData>", Pattern.DOTALL);
    private static final Pattern NAME_ATTR =
            Pattern.compile("<twClass\\b[^>]*name=\"([^\"]*)\"");
    private static final int MAX_DEPTH = 30;
    private static final int MAX_PROPS = 400;

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Map<Identity, BusinessData> CACHE = new WeakHashMap<>();

    private record Identity(TwxParseResult ref) {
        @Override
        public boolean equals(Object o) {
            return o instanceof Identity i && i.ref == ref;
        }

        @Override
        public int hashCode() {
            return System.identityHashCode(ref);
        }
    }

    public static synchronized BusinessData of(TwxParseResult parsed) {
        return CACHE.computeIfAbsent(new Identity(parsed), id -> new BusinessData(parsed));
    }

    private final List<Type> types = new ArrayList<>();

    private BusinessData(TwxParseResult parsed) {
        for (var o : parsed.objects()) {
            if (!"12".equals(o.prefix()) || o.content() == null) {
                continue;
            }
            Type t = parse(o);
            if (t != null) {
                types.add(t);
            }
        }
    }

    public List<Type> types() {
        return types;
    }

    private static Type parse(TwxParseResult.ParsedObject o) {
        Matcher jd = JSON_DATA.matcher(o.content());
        if (!jd.find()) {
            return null;
        }
        JsonNode root;
        try {
            root = MAPPER.readTree(unesc(jd.group(1)));
        } catch (Exception e) {
            return null; // no readable schema - treated as nonexistent by the rules
        }
        if (root == null || !root.isObject()) {
            return null;
        }
        Matcher nm = NAME_ATTR.matcher(o.content());
        String name = nm.find() ? nm.group(1) : o.name() != null ? o.name() : o.id();
        boolean wrapper = root.has("rootElement");
        boolean imported = root.path("targetNamespace").asText("").contains("externalservice/swagger");
        boolean shared = hasShared(root, 0);
        List<Prop> props = new ArrayList<>();
        collectProps(root, props, 0);
        return new Type(o, name, wrapper, imported, shared, rootHasDoc(root), props);
    }

    /** promoted to shared: appinfo.shared == true (depth search over the whole schema JSON). */
    private static boolean hasShared(JsonNode node, int depth) {
        if (depth > MAX_DEPTH) {
            return false;
        }
        if (node.isObject()) {
            Iterator<Map.Entry<String, JsonNode>> it = node.fields();
            while (it.hasNext()) {
                Map.Entry<String, JsonNode> e = it.next();
                if ("shared".equals(e.getKey()) && isTrue(e.getValue())) {
                    return true;
                }
                if (hasShared(e.getValue(), depth + 1)) {
                    return true;
                }
            }
        } else if (node.isArray()) {
            for (JsonNode c : node) {
                if (hasShared(c, depth + 1)) {
                    return true;
                }
            }
        }
        return false;
    }

    private static boolean isTrue(JsonNode v) {
        if (v.isBoolean()) {
            return v.asBoolean();
        }
        return v.isArray() && v.size() == 1 && v.get(0).isBoolean() && v.get(0).asBoolean();
    }

    /** recursively collect named element/attribute nodes (XSD JSON, arbitrary depth). */
    private static void collectProps(JsonNode node, List<Prop> out, int depth) {
        if (depth > MAX_DEPTH || out.size() >= MAX_PROPS) {
            return;
        }
        if (node.isObject()) {
            Iterator<Map.Entry<String, JsonNode>> it = node.fields();
            while (it.hasNext() && out.size() < MAX_PROPS) {
                Map.Entry<String, JsonNode> e = it.next();
                if ("element".equals(e.getKey()) || "attribute".equals(e.getKey())) {
                    for (JsonNode item : listify(e.getValue())) {
                        if (item.isObject() && item.path("name").isTextual()) {
                            out.add(new Prop(item.get("name").asText(),
                                    item.path("type").isTextual() ? item.get("type").asText() : null,
                                    hasDoc(item.get("annotation"))));
                        }
                        collectProps(item, out, depth + 1);
                        if (out.size() >= MAX_PROPS) {
                            return;
                        }
                    }
                } else {
                    collectProps(e.getValue(), out, depth + 1);
                }
            }
        } else if (node.isArray()) {
            for (JsonNode c : node) {
                collectProps(c, out, depth + 1);
            }
        }
    }

    /**
     * Root documentation: documentation entry on the type itself (complexType
     * entries or the root element, depending on serialization).
     */
    private static boolean rootHasDoc(JsonNode root) {
        List<JsonNode> roots = new ArrayList<>();
        if (root.has("complexType")) {
            listify(root.get("complexType")).forEach(roots::add);
        } else if (root.has("element")) {
            listify(root.get("element")).forEach(roots::add);
        } else {
            roots.add(root);
        }
        for (JsonNode r : roots) {
            if (r.isObject() && hasDoc(r.get("annotation"))) {
                return true;
            }
        }
        return false;
    }

    /** annotation.documentation with at least one real text value (format: content array). */
    private static boolean hasDoc(JsonNode annotation) {
        if (annotation == null || !annotation.isObject()) {
            return false;
        }
        JsonNode doc = annotation.get("documentation");
        if (doc == null) {
            return false;
        }
        for (JsonNode entry : listify(doc)) {
            if (entry.isTextual() && !entry.asText().isEmpty()) {
                return true;
            }
            if (entry.isObject()) {
                Iterator<JsonNode> it = entry.elements();
                while (it.hasNext()) {
                    if (isDocValue(it.next())) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /** Value of a documentation entry: empty ({}, [], [{}], "") is not documentation. */
    private static boolean isDocValue(JsonNode v) {
        if (v == null || v.isMissingNode() || v.isNull()) {
            return false;
        }
        if (v.isTextual()) {
            return !v.asText().isEmpty();
        }
        if (v.isObject()) {
            return v.size() > 0;
        }
        if (v.isArray()) {
            if (v.isEmpty() || (v.size() == 1 && v.get(0).isObject() && v.get(0).isEmpty())) {
                return false;
            }
            return true;
        }
        return true;
    }

    private static List<JsonNode> listify(JsonNode v) {
        List<JsonNode> l = new ArrayList<>();
        if (v.isArray()) {
            v.forEach(l::add);
        } else if (v.isObject() && !v.isEmpty()) {
            l.add(v);
        }
        return l;
    }

    static String unesc(String s) {
        if (s == null || s.indexOf('&') < 0) {
            return s == null ? "" : s;
        }
        return s.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"")
                .replace("&apos;", "'").replace("&#xD;", "\r").replace("&#13;", "\r")
                .replace("&#xA;", "\n").replace("&#10;", "\n").replace("&amp;", "&");
    }
}

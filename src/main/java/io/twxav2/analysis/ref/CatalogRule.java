package io.twxav2.analysis.ref;

import io.twxav2.analysis.RuleContext;
import io.twxav2.analysis.RuleSettings;
import io.twxav2.analysis.TwxRule;
import io.twxav2.analysis.ref.rules.Finding;
import io.twxav2.analysis.ref.rules.Rule;
import io.twxav2.ingest.TwxParseResult;
import io.twxav2.model.Finding.Severity;

import java.util.ArrayList;
import java.util.List;

/**
 * Adapter: a reference-catalog rule as a house {@link TwxRule} bean.
 * Carries the rule's catalog id (R-&lt;KAT&gt;-&lt;nnn&gt;), takes
 * severity/impact from the
 * rule and serves title/category/description/remediation in German
 * ({@link RuleTextsDe}, falls back to English); the original text ships as
 * the {@code *En} field. Finding messages stay in English.
 *
 * <p>The expensive reference context (model + modeled objects) is shared once per
 * rule run in the {@code scratch} of the {@link RuleContext}.
 */
public class CatalogRule implements TwxRule {

    /** Key of the shared reference rule context in the run scratch. */
    static final String SCRATCH_KEY = "ref.rules.RuleContext";

    private final String id;
    private final Rule ref;

    public CatalogRule(String id, Rule ref) {
        this.id = id;
        this.ref = ref;
    }

    /** The wrapped catalog rule (tooling for tests and catalog display texts). */
    public Rule ref() {
        return ref;
    }

    /** Returns the run's shared reference rule context, building it on first use. */
    public static io.twxav2.analysis.ref.rules.RuleContext refContext(RuleContext ctx) {
        return (io.twxav2.analysis.ref.rules.RuleContext) ctx.scratch()
                .computeIfAbsent(SCRATCH_KEY,
                        k -> new io.twxav2.analysis.ref.rules.RuleContext(
                                RefModel.from(ctx.parsed()), ctx.thresholds(), false));
    }

    @Override
    public String id() {
        return id;
    }

    @Override
    public String title() {
        return RuleTextsDe.or(id, "title", ref.title);
    }

    @Override
    public String titleEn() {
        return ref.title;
    }

    @Override
    public String category() {
        return RuleTextsDe.or(id, "category", ref.category);
    }

    @Override
    public String categoryEn() {
        return ref.category;
    }

    @Override
    public Severity defaultSeverity() {
        return Severity.valueOf(ref.severity.name());
    }

    @Override
    public int impact() {
        return ref.impact;
    }

    @Override
    public String rationale() {
        return RuleTextsDe.or(id, "rationale", ref.description);
    }

    @Override
    public String rationaleEn() {
        return ref.description;
    }

    @Override
    public String guidance() {
        return RuleTextsDe.or(id, "guidance", ref.remediation);
    }

    @Override
    public String guidanceEn() {
        return ref.remediation;
    }

    @Override
    public List<Hit> analyze(RuleContext ctx) {
        io.twxav2.analysis.ref.rules.RuleContext rc = refContext(ctx);
        List<Finding> out = new ArrayList<>();
        ref.check(rc, out);
        List<Hit> hits = new ArrayList<>(out.size());
        for (Finding f : out) {
            if (isDesignerGenerated(f.objectName)) {
                continue; // wrapper classes generated by the Designer are not editable
            }
            hits.add(toHit(f));
        }
        return hits;
    }

    /**
     * Process Designer-generated wrapper classes for service/REST payloads
     * (Msg_&lt;hash&gt;_&lt;GUID&gt;, ItmDef_&lt;hash&gt;_&lt;GUID&gt;, prefix 12).
     * They are not visible or editable as objects in the Designer; findings
     * about them (documentation, naming, unused, reference rules) cannot be fixed.
     */
    private static final java.util.regex.Pattern GENERATED_OBJECT = java.util.regex.Pattern
            .compile("^(?:Msg|ItmDef)_\\d+_[0-9a-f]{8}(?:_[0-9a-f]{4}){3}_[0-9a-f]{12}$");

    static boolean isDesignerGenerated(String objectName) {
        return objectName != null && GENERATED_OBJECT.matcher(objectName).matches();
    }

    @Override
    public List<Hit> analyze(TwxParseResult result) {
        return analyze(new RuleContext(result, RuleSettings.DEFAULT_THRESHOLDS));
    }

    /** Catalog finding -> house hit: location/line/snippet, evidence appended to the message, review flag. */
    static Hit toHit(Finding f) {
        String message = f.message;
        if (!f.evidence.isEmpty()) {
            message = message + " — " + f.evidence;
        }
        if (message.length() > 590) {
            message = message.substring(0, 590) + "...";
        }
        return new Hit(Severity.valueOf(f.severity),
                f.objectId.isEmpty() ? null : f.objectId,
                f.objectName.isEmpty() ? null : f.objectName,
                message,
                f.location.isEmpty() ? null : f.location,
                f.line > 0 ? f.line : null,
                f.snippet.isEmpty() ? null : f.snippet,
                !"high".equals(f.confidence),
                message);
    }
}

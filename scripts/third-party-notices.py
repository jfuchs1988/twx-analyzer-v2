#!/usr/bin/env python3
"""Generate the checked-in third-party inventory from Maven/npm lock metadata."""

import json
import re
from collections import Counter
from datetime import date
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MAVEN_RUNTIME_REPORT = ROOT / "target/license-audit/THIRD-PARTY.txt"
MAVEN_REPORT = ROOT / "target/license-audit/all/THIRD-PARTY.txt"
NPM_LOCK = ROOT / "frontend/package-lock.json"
OUTPUT = ROOT / "docs/THIRD-PARTY-NOTICES.md"


def markdown_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def main() -> None:
    def read_maven_report(path: Path) -> list[str]:
        if not path.is_file():
            raise SystemExit(f"Missing Maven inventory report: {path.relative_to(ROOT)}")
        report_lines = path.read_text(encoding="utf-8").splitlines()
        match = re.search(r"Lists of (\d+) third-party dependencies\.", "\n".join(report_lines))
        entries = [line.strip() for line in report_lines if re.match(r"^\s+\(", line)]
        if not match or len(entries) != int(match.group(1)):
            raise SystemExit(f"Maven inventory count did not match report: {path.relative_to(ROOT)}")
        return entries

    maven_runtime_entries = read_maven_report(MAVEN_RUNTIME_REPORT)
    maven_entries = read_maven_report(MAVEN_REPORT)

    lock = json.loads(NPM_LOCK.read_text(encoding="utf-8"))
    npm_entries = [
        (path, package)
        for path, package in lock["packages"].items()
        if path.startswith("node_modules/")
    ]
    missing = [path for path, package in npm_entries if not package.get("license")]
    if missing:
        raise SystemExit("Missing npm license metadata: " + ", ".join(missing))

    npm_licenses = Counter(str(package["license"]) for _, package in npm_entries)
    lines = [
        "# Third-Party Software Notices",
        "",
        f"**Review date:** {date.today().isoformat()}",
        "**Scope:** Maven project dependencies in all declared scopes, and every package in `frontend/package-lock.json`.",
        "",
        "This inventory records license declarations from resolved Maven POM metadata and npm lockfile/package metadata; it is not legal advice or an independent opinion on license compatibility. Maven's report includes test-scoped artifacts as well as application dependencies. npm entries marked `dev-only` are build/test tooling and are not runtime UI dependencies. Re-review this inventory whenever `pom.xml`, Maven dependency management, `frontend/package.json`, or `frontend/package-lock.json` changes.",
        "",
        "## Distribution and attribution notes",
        "",
        "- Preserve the project [`LICENSE`](../LICENSE) and [`NOTICE`](../NOTICE), including the TWX Code Analyzer provenance and attribution, when redistributing source or the container image.",
        "- The distributed Quarkus application contains third-party JARs as separate, unmodified artifacts. In particular, MariaDB Connector/J 3.5.10 declares LGPL-2.1-or-later and Mozilla Rhino 1.9.1 declares MPL-2.0. Keep their artifact/source identity and license terms available to recipients; do not shade, modify, or strip notices without reviewing the applicable license requirements. Artifact links are present in the Maven inventory below.",
        "- Other Maven metadata declares Apache-2.0, EPL/EDL (some with alternative GPL-plus-classpath-exception terms), BSD, MIT, and public-domain licenses. Preserve the upstream license and attribution notices for each redistributed artifact; the Maven report records its coordinates and project URL.",
        "- The frontend lockfile contains multiple permissive, public-domain, and notice-based license declarations. Its exact license expressions and counts, with package versions and resolved registry sources, are listed below; source package links lead to the registry tarballs with their upstream files.",
        "- The container image copies this file alongside `LICENSE` and `NOTICE`. This inventory does not replace the license files inside third-party packages or fulfill source-offer obligations by itself.",
        "",
        "## Maven dependencies",
        "",
        f"Resolved packaged-scope Maven inventory: **{len(maven_runtime_entries)} artifacts** in `compile`/`runtime` scopes. Generated by `org.codehaus.mojo:license-maven-plugin:2.7.1:add-third-party` from resolved Maven POM metadata.",
        "",
        "| Declared license, artifact, coordinates, and project URL (as reported by Maven) |",
        "| --- |",
    ]
    lines.extend(f"| {markdown_cell(entry)} |" for entry in maven_runtime_entries)
    lines.extend(
        [
            "",
            f"All-scope Maven audit: **{len(maven_entries)} artifacts**, including test-scoped project dependencies. This wider list documents the full declared Maven project graph; test-only artifacts are not part of the packaged application.",
            "",
            "| Declared license, artifact, coordinates, and project URL (as reported by Maven) |",
            "| --- |",
        ]
    )
    lines.extend(f"| {markdown_cell(entry)} |" for entry in maven_entries)
    lines.extend(
        [
            "",
            "## npm dependencies",
            "",
            f"Resolved npm inventory: **{len(npm_entries)} packages**. License distribution in the lockfile: "
            + "; ".join(f"`{license}`: {count}" for license, count in sorted(npm_licenses.items()))
            + ".",
            "",
            "| Package | Version | Declared license | Scope | Resolved package source |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for path, package in sorted(npm_entries):
        name = path.rsplit("node_modules/", 1)[-1]
        source = package.get("resolved", "")
        source_link = f"[package]({source})" if source else "not recorded"
        scope = "dev-only" if package.get("dev") else "runtime or shared"
        lines.append(
            "| "
            + " | ".join(
                markdown_cell(str(value))
                for value in (name, package.get("version", "unknown"), package["license"], scope)
            )
            + f" | {source_link} |"
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"Wrote {OUTPUT.relative_to(ROOT)} "
        f"({len(maven_runtime_entries)} runtime Maven, {len(maven_entries)} all-scope Maven, "
        f"{len(npm_entries)} npm entries)"
    )


if __name__ == "__main__":
    main()
